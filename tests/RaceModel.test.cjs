'use strict';
const assert=require('node:assert/strict');
const {RaceModel}=require('../.test/RaceModel.js');
const tick=(m, seconds=30)=>{for(let i=0;i<Math.ceil(seconds*10);i++)m.update(0.1)};
const m=new RaceModel(()=>0.3);
assert.equal(m.cells.length,15,'default should be 15 unordered pairs');
assert.equal(new Set(m.cells.map(c=>c.key)).size,15);
assert.equal(m.getCell('4-3').key,'3-4');
assert.equal(m.credits,500);
assert.equal(m.placeBet('3-4',10),true);
assert.equal(m.placeBet('4-3',5),true);
assert.equal(m.totalStake,15);
assert.equal(m.credits,485);
assert.equal(m.placeBet('3-4',-5),true);
assert.equal(m.getCell('3-4').stake,10);
assert.equal(m.credits,490);
assert.equal(m.startRace(),true);
assert.equal(m.phase,'racing');
assert.equal(m.placeBet('1-2',1),false,'should lock betting during race');
tick(m,22);
assert.equal(m.phase,'result');
assert.deepEqual(m.lastResult.order.slice(0,2),[4,3]);
assert.equal(m.lastResult.pair,'3-4');
assert.equal(m.lastResult.payout,10*m.getCell('3-4').odds);
assert.equal(m.credits,490+m.lastResult.payout);
assert.equal(m.history.length,1);
assert.equal(m.startRace(),true);
assert.equal(m.phase,'betting');
assert.equal(m.totalStake,0);
assert.equal(m.history.length,1);
assert.equal(m.countdown,30);
assert.equal(m.placeBet('1-2',2),true);
assert.equal(m.credits,490+400-2);
m.clearBets();
assert.equal(m.totalStake,0);
assert.equal(m.credits,890);
assert.equal(m.placeBet('1-2',-1),false);
assert.equal(m.placeBet('1-2',0.5),false);
assert.equal(m.placeBet('2-2',1),false);
const ordered=new RaceModel(()=>0.3,{pairMode:'ordered'});
assert.equal(ordered.cells.length,30);
assert.notEqual(ordered.getCell('1-2'),ordered.getCell('2-1'));
const autoplay=new RaceModel(()=>0.3,{bettingSeconds:1});
autoplay.placeBet('1-2',1);tick(autoplay,1.5);
assert.equal(autoplay.phase,'racing','timer should start if bet exists');
console.log('RaceModel: 20+ assertions passed; default=15 pairs; optional=30 ordered; settlement works.');
